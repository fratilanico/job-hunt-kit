#!/usr/bin/env node
// CV builder: one HTML structure, five token themes, headless Chromium -> A4 PDF, then the ATS check.
//
//   node cv/build.mjs                                   # profile/cv.yaml (or the sample) with the profile's theme
//   node cv/build.mjs --content profile/cv.yaml --theme editorial --out cv/out/cv.pdf
//   node cv/build.mjs --theme boardroom --bw            # print-safe black-and-white variant of a theme
//   node cv/build.mjs --accent "#1d4ed8"                # custom accent colour
//   node cv/build.mjs --calm | --no-calm                # fewer accent uses (auto for director-level roles)
//   node cv/build.mjs --role "Head of Communications"   # picks theme + calm via recommendTheme when --theme is absent
//   node cv/build.mjs --png                             # also writes <out>-p1.png (page 1) for a visual check
//   node cv/build.mjs --previews [--content x.yaml] [--out-dir dir]   # page 1 of all 5 themes + a side-by-side sheet
//   node cv/build.mjs --recommend "Role title" [--seniority director]
//   node cv/build.mjs --emit-bw                         # regenerate cv/themes/<name>.bw.css from the token files
//
// Layout is overflow-safe: content is cut into atoms and a paginator fills fixed A4 pages in order,
// keeping headings with what follows. Anything that still does not fit is reported and fails the ATS check.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import YAML from 'yaml';
import { chromium } from 'playwright';
import { THEMES, recommendTheme } from './themes.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.dirname(HERE);
const args = process.argv.slice(2);
const has = k => args.includes(k);
const opt = (k, d) => { const i = args.indexOf(k); return i > -1 && args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : d; };

function loadProfile() {
  const p = process.env.JOBKIT_PROFILE || path.join(ROOT, 'profile/profile.yaml');
  try { return YAML.parse(fs.readFileSync(p, 'utf8')) || {}; } catch { return {}; }
}
const profile = loadProfile();
const pcv = profile.cv || {};

// ---------- black-and-white override generated from a theme's tokens ----------
function hexToRgb(h) {
  h = h.replace('#', ''); if (h.length === 3) h = h.split('').map(c => c + c).join('');
  return [0, 2, 4].map(i => parseInt(h.slice(i, i + 2), 16));
}
const lum = ([r, g, b]) => Math.round((0.2126 * r + 0.7152 * g + 0.0722 * b) / 2.55); // 0..100
const grey = L => { const v = Math.round(Math.max(0, Math.min(100, L)) * 2.55).toString(16).padStart(2, '0'); return `#${v}${v}${v}`; };
export function bwFrom(css, dark) {
  const SURFACE = /^--(page-bg|page-bg-alt|surface|band-bg|role-bg|tag-bg|badge-bg)$/;
  const LINE = /line|border|divider|rule/;
  const map = (name, hex) => {
    let L = lum(hexToRgb(hex)); if (dark) L = 100 - L;
    if (name === '--page-bg' || name === '--page-bg-alt') return '#ffffff';
    if (name === '--accent') return '#000000';
    if (SURFACE.test(name)) return grey(Math.max(L, 93));
    if (LINE.test(name)) return grey(Math.min(Math.max(L, 55), 82));
    if (/ink-faint|ink-muted|contact-ink/.test(name)) return grey(Math.min(L, 42));
    return grey(Math.min(L, 22)); // text, accents, badges ink: print dark
  };
  const out = [];
  const tokRx = /(--[\w-]+)\s*:\s*([^;]+);/g;
  const root = css.match(/:root\s*\{([\s\S]*?)\}/);
  if (root) {
    for (const [, name, val] of root[1].matchAll(tokRx)) {
      if (/shadow|glow/.test(name)) { out.push(`  ${name}: none;`); continue; }
      let v = val.replace(/color-mix\((?:[^()]|\([^()]*\))*\)/g, () => map(name, /accent/.test(name) ? '#000000' : (SURFACE.test(name) ? '#f2f2f2' : '#888888')));
      v = v.replace(/#[0-9a-fA-F]{3,6}\b/g, h => map(name, h));
      if (/^--(page-bg|page-bg-alt)$/.test(name)) v = '#ffffff';
      if (v !== val) out.push(`  ${name}: ${v.trim()};`);
    }
  }
  // non-token rules: recolour hard-coded colours to dark grey
  const rest = css.replace(/:root\s*\{[\s\S]*?\}/, '').replace(/\/\*[\s\S]*?\*\//g, '').trim();
  const restBw = rest.replace(/#[0-9a-fA-F]{3,6}\b/g, '#222222').replace(/var\(--accent\)/g, '#222222');
  return `/* GENERATED by cv/build.mjs --emit-bw: print-safe black-and-white override. Do not edit; edit the theme and regenerate. */\n:root {\n  --accent-hl: #000000;\n${out.join('\n')}\n}\n${restBw && restBw !== rest ? restBw + '\n' : ''}`;
}
function emitBw() {
  for (const name of Object.keys(THEMES)) {
    const css = fs.readFileSync(path.join(HERE, 'themes', name + '.css'), 'utf8');
    fs.writeFileSync(path.join(HERE, 'themes', name + '.bw.css'), bwFrom(css, THEMES[name].ground === 'dark'));
    console.log('wrote', `cv/themes/${name}.bw.css`);
  }
}

// ---------- content -> atoms ----------
const esc = s => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const inline = s => esc(s).replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>').replace(/\[\[(.+?)\]\]/g, '<span class="accent">$1</span>');
const plain = s => String(s ?? '').replace(/\*\*|\[\[|\]\]/g, '');

export function atomsFor(c) {
  const A = [];
  const atom = (html, wrap = [], keep = false) => A.push({ html, wrap, keep });
  let n = 0;
  const title = (label, first = false) => { n += 1; atom(`<h2 class="section-title${first ? ' first' : ''}"><span class="num">${String(n).padStart(2, '0')}</span><span class="label">${esc(label)}</span></h2>`, [], true); };
  const ct = c.contact || {};
  const contact = [ct.location, ct.phone, ct.email && `<a href="mailto:${esc(ct.email)}">${esc(ct.email)}</a>`, ct.linkedin, ct.github, ct.website]
    .filter(Boolean).map(x => `<span>${/^<a /.test(x) ? x : esc(x)}</span>`).join('');
  atom(`<header class="cv-header"><h1>${esc(c.name)}</h1>${c.headline ? `<div class="headline">${esc(c.headline)}</div>` : ''}<div class="contact">${contact}</div></header><div class="rule"></div>`, [], true);
  let first = true;
  if (c.summary?.length) { title(c.summary_title || 'Professional Summary', first); first = false; for (const p of [].concat(c.summary)) atom(`<p>${inline(p)}</p>`); }
  if (c.skills?.length) {
    title(c.skills_title || 'Core Skills', first); first = false;
    atom(`<div class="skills">${c.skills.map(s => `<article class="skill"><h3>${esc(s.title)}</h3><p>${inline(s.body)}</p></article>`).join('')}</div>`);
    if (c.approach?.text) atom(`<div class="approach"><h3>${esc(c.approach.title || 'How I Work')}</h3><p>${inline(c.approach.text)}</p></div>`);
    if (c.tags?.length) atom(`<div class="tags">${c.tags.map(t => `<span class="tag">${esc(t)}</span>`).join('')}</div>`);
  }
  if (c.projects?.length) {
    title(c.projects_title || 'Projects', first); first = false;
    c.projects.forEach((p, i) => {
      const card = { tag: 'div', cls: 'project', key: 'p' + i };
      atom(`<div class="project-head"><h3>${esc(p.title)}</h3>${p.badge ? `<span class="badge">${esc(p.badge)}</span>` : ''}</div>`, [card], true);
      for (const b of p.bullets || []) atom(`<li>${inline(b)}</li>`, [card, { tag: 'ul', key: 'pu' + i }]);
    });
  }
  if (c.experience?.length) {
    title(c.experience_title || 'Professional Experience', first); first = false;
    const exp = { tag: 'div', cls: 'experience', key: 'exp' };
    c.experience.forEach((j, i) => {
      const job = { tag: 'article', cls: 'job', key: 'j' + i };
      atom(`<div class="job-head"><h3>${esc(j.company)}</h3><span class="date">${esc(j.date)}</span></div>`, [exp, job], true);
      if (j.role) atom(`<div class="roleline">${esc(j.role)}</div>`, [exp, job], true);
      for (const b of j.bullets || []) atom(`<li>${inline(b)}</li>`, [exp, job, { tag: 'ul', key: `ju${i}` }]);
      (j.subroles || []).forEach((s, k) => {
        atom(`<div class="subrole">${esc(s.title)}</div>`, [exp, job], true);
        for (const b of s.bullets || []) atom(`<li>${inline(b)}</li>`, [exp, job, { tag: 'ul', key: `ju${i}s${k}` }]);
      });
    });
  }
  for (const s of c.sections || []) { // free-form extra sections: { title, paragraphs?, bullets? }
    title(s.title, first); first = false;
    for (const p of s.paragraphs || []) atom(`<p>${inline(p)}</p>`);
    for (const b of s.bullets || []) atom(`<li>${inline(b)}</li>`, [{ tag: 'ul', key: 'x' + n }]);
  }
  if (c.footer?.length) atom(`<div class="footer-grid" style="--footer-cols:${Math.min(c.footer.length, 4)}">${c.footer.map(f => `<div><h3>${esc(f.title)}</h3><p>${(f.lines || []).map(esc).join('<br>')}</p></div>`).join('')}</div>`);
  return A;
}

// Strings the ATS check expects to find, in reading order where it matters.
export function expectations(c) {
  const ct = c.contact || {};
  const headings = [];
  if (c.summary?.length) headings.push({ h: c.summary_title || 'Professional Summary', first: plain([].concat(c.summary)[0]) });
  if (c.skills?.length) headings.push({ h: c.skills_title || 'Core Skills', first: c.skills[0].title });
  if (c.projects?.length) headings.push({ h: c.projects_title || 'Projects', first: c.projects[0].title });
  if (c.experience?.length) headings.push({ h: c.experience_title || 'Professional Experience', first: c.experience[0].company });
  for (const s of c.sections || []) headings.push({ h: s.title, first: plain((s.paragraphs || s.bullets || [''])[0]) });
  const jobs = (c.experience || []).map(j => ({ company: j.company, role: j.role, date: j.date }));
  const cards = (c.skills || []).map(s => ({ title: s.title, body: plain(s.body) }));
  return { name: c.name, email: ct.email, phone: ct.phone, headings, jobs, cards, cardsHeading: c.skills?.length ? (c.skills_title || 'Core Skills') : '' };
}

const PAGINATE = `(${function paginate(name) {
  const staging = document.getElementById('staging'); const root = document.getElementById('pages');
  const atoms = [...staging.children]; const pages = []; const overflow = [];
  let page, stack, onPage;
  const newPage = () => {
    page = document.createElement('section'); page.className = 'page'; root.appendChild(page); pages.push(page); stack = []; onPage = [];
    if (pages.length > 1) { const r = document.createElement('div'); r.className = 'running'; r.innerHTML = '<span></span><span></span>'; r.firstChild.textContent = name; page.appendChild(r); }
  };
  const over = () => page.scrollHeight > page.clientHeight + 1;
  const place = a => {
    const wrap = JSON.parse(a.dataset.wrap || '[]');
    stack = stack.filter(s => s.el.isConnected);
    let i = 0; while (i < stack.length && i < wrap.length && stack[i].key === wrap[i].key) i++;
    stack.length = i; let parent = i ? stack[i - 1].el : page;
    for (; i < wrap.length; i++) { const el = document.createElement(wrap[i].tag || 'div'); if (wrap[i].cls) el.className = wrap[i].cls; parent.appendChild(el); stack.push({ key: wrap[i].key, el }); parent = el; }
    parent.appendChild(a); onPage.push(a);
  };
  const unplace = a => {
    let p = a.parentElement; a.remove(); onPage.splice(onPage.indexOf(a), 1);
    while (p && p !== page && !p.children.length) { const q = p.parentElement; p.remove(); p = q; }
    stack = stack.filter(s => s.el.isConnected);
  };
  newPage();
  for (const a of atoms) {
    place(a);
    if (!over()) continue;
    const chain = [a]; for (let k = onPage.length - 2; k >= 0 && onPage[k].dataset.keep === '1'; k--) chain.unshift(onPage[k]);
    if (chain.length === onPage.length) { overflow.push((a.textContent || '').trim().slice(0, 80)); continue; }
    for (const x of [...chain].reverse()) unplace(x);
    newPage(); for (const x of chain) place(x);
    if (over()) overflow.push((a.textContent || '').trim().slice(0, 80));
  }
  const fill = pages.map(p => { const top = p.getBoundingClientRect().top; const pad = parseFloat(getComputedStyle(p).paddingBottom);
    const bottom = Math.max(0, ...[...p.querySelectorAll('*')].map(e => e.getBoundingClientRect().bottom - top));
    return +(bottom / (p.clientHeight - pad)).toFixed(2); });
  pages.forEach((p, i) => { if (i && p.querySelector('.running span:last-child')) p.querySelector('.running span:last-child').textContent = `Page ${i + 1} of ${pages.length}`; if (p.scrollHeight > p.clientHeight + 1 && !overflow.length) overflow.push('page ' + (i + 1)); });
  staging.remove();
  return { pages: pages.length, overflow, fill };
}})`;

function htmlFor(c, { theme, bw, accent, calm }) {
  const css = ['base.css', `themes/${theme}.css`].concat(bw ? [`themes/${theme}.bw.css`] : []).map(f => fs.readFileSync(path.join(HERE, f), 'utf8')).join('\n');
  const acc = accent && /^#[0-9a-f]{3,8}$/i.test(accent) && !bw ? `:root{--accent:${accent}}` : '';
  const atoms = atomsFor(c).map(a => {
    const tmp = a.html.trim(); const m = tmp.match(/^<(\w+)/);
    // single-root atoms carry the data attributes directly; multi-root atoms are wrapped
    const single = m && tmp.endsWith(`</${m[1]}>`) && (tmp.match(new RegExp(`<${m[1]}[\\s>]`, 'g')) || []).length === 1;
    const attrs = ` data-wrap='${esc(JSON.stringify(a.wrap))}' data-keep="${a.keep ? 1 : 0}"`;
    return single ? tmp.replace(/^<(\w+)/, `<$1${attrs}`) : `<div${attrs}>${tmp}</div>`;
  }).join('\n');
  return `<!doctype html><html lang="en" class="${calm ? 'calm' : ''}"><head><meta charset="utf-8"><title>${esc(c.name)} CV</title><style>${css}\n${acc}</style></head>
<body><div id="pages"></div><div id="staging">${atoms}</div></body></html>`;
}

// Headless Google Chrome if installed (CHROME_CHANNEL=chrome by default), else Playwright's bundled Chromium.
export async function launchBrowser() {
  const ch = process.env.CHROME_CHANNEL ?? 'chrome';
  if (ch) { try { return await chromium.launch({ channel: ch }); } catch {} }
  return chromium.launch();
}

async function render(browser, c, o) {
  const page = await browser.newPage({ viewport: { width: 900, height: 1200 } });
  await page.setContent(htmlFor(c, o), { waitUntil: 'load' });
  await page.evaluate(() => document.fonts.ready);
  const layout = await page.evaluate(`${PAGINATE}(${JSON.stringify(c.name || '')})`);
  return { page, layout };
}

function resolveTheme() {
  let theme = opt('--theme'), calm = has('--calm') ? true : has('--no-calm') ? false : undefined, why = '';
  if (!theme && opt('--role')) { const r = recommendTheme(opt('--role'), opt('--seniority', '')); theme = r.theme; why = r.why; if (calm === undefined) calm = r.calm; }
  theme ||= pcv.theme || 'editorial';
  if (!THEMES[theme]) { console.error('unknown theme ' + theme + '; choose ' + Object.keys(THEMES).join(' | ')); process.exit(2); }
  return { theme, calm: !!calm, why };
}

function contentPath() {
  const cands = [opt('--content'), pcv.source && path.join(ROOT, pcv.source), path.join(ROOT, 'profile/cv.yaml'), path.join(HERE, 'sample-content.yaml')].filter(Boolean);
  const p = cands.find(f => fs.existsSync(f));
  if (!p) { console.error('no CV content found'); process.exit(2); }
  return p;
}

async function main() {
  if (has('--emit-bw')) return emitBw();
  if (has('--recommend')) { console.log(JSON.stringify(recommendTheme(opt('--recommend', ''), opt('--seniority', '')), null, 1)); return; }
  const cpath = contentPath();
  const c = YAML.parse(fs.readFileSync(cpath, 'utf8'));
  const browser = await launchBrowser();
  let failed = false;
  try {
    if (has('--previews')) {
      const dir = path.resolve(opt('--out-dir', path.join(HERE, 'themes/previews'))); fs.mkdirSync(dir, { recursive: true });
      const shots = [];
      for (const theme of Object.keys(THEMES)) for (const bw of has('--with-bw') ? [false, true] : [false]) {
        const base = path.join(dir, theme + (bw ? '-bw' : ''));
        const { page, layout } = await render(browser, c, { theme, bw, accent: opt('--accent'), calm: has('--calm') });
        await page.pdf({ path: base + '.pdf', preferCSSPageSize: true, printBackground: true });
        fs.writeFileSync(base + '.layout.json', JSON.stringify(layout));
        await page.locator('.page').first().screenshot({ path: base + '.png' });
        await page.close();
        const ok = check(base + '.pdf', c, cpath);
        failed ||= !ok; if (!bw) shots.push({ theme, png: base + '.png', ok });
        if (!has('--keep-pdf')) { fs.rmSync(base + '.pdf'); fs.rmSync(base + '.layout.json'); }
      }
      const rec = recommendTheme(opt('--role', ''), opt('--seniority', ''));
      const sheet = await browser.newPage({ viewport: { width: 2000, height: 700 } });
      await sheet.setContent(`<body style="margin:0;padding:24px;background:#e9e9e9;font:14px Arial;display:flex;gap:16px">${shots.map(s =>
        `<figure style="margin:0;flex:1"><img src="data:image/png;base64,${fs.readFileSync(s.png).toString('base64')}" style="width:100%;box-shadow:0 1px 6px #0003"><figcaption style="margin-top:8px"><b>${s.theme}</b>${s.theme === rec.theme ? ' (recommended)' : ''}<br>${THEMES[s.theme].for}</figcaption></figure>`).join('')}</body>`);
      await sheet.screenshot({ path: path.join(dir, 'all-themes.png'), fullPage: true });
      console.log('previews ->', dir, has('--role') ? `\nrecommended: ${rec.theme} (${rec.why})` : '');
    } else {
      const { theme, calm, why } = resolveTheme();
      const bw = has('--bw');
      const out = path.resolve(opt('--out', pcv.default_pdf ? path.join(ROOT, pcv.default_pdf) : path.join(ROOT, 'cv/out/cv.pdf')));
      fs.mkdirSync(path.dirname(out), { recursive: true });
      const { page, layout } = await render(browser, c, { theme, bw, accent: opt('--accent', pcv.accent), calm });
      await page.pdf({ path: out, preferCSSPageSize: true, printBackground: true });
      fs.writeFileSync(out.replace(/\.pdf$/, '.layout.json'), JSON.stringify(layout));
      if (has('--png')) await page.locator('.page').first().screenshot({ path: out.replace(/\.pdf$/, '-p1.png') });
      if (has('--html')) fs.writeFileSync(out.replace(/\.pdf$/, '.html'), await page.content());
      await page.close();
      console.log(`built ${path.relative(ROOT, out)}  theme=${theme}${bw ? ' bw' : ''}${calm ? ' calm' : ''}  pages=${layout.pages}  fill=${layout.fill.join('/')}${why ? `\n  theme reason: ${why}` : ''}`);
      if (layout.fill.length > 1 && layout.fill.at(-1) < 0.35) console.log('  note: last page is under a third full; trim to fewer pages or add substance');
      if (!has('--no-check')) failed = !check(out, c, cpath);
    }
  } finally { await browser.close(); }
  process.exit(failed ? 1 : 0);
}

function check(pdf, c, cpath) {
  const max = opt('--max-pages', pcv.max_pages || 3);
  const r = spawnSync(process.execPath, [path.join(HERE, 'ats-check.mjs'), pdf, '--content', cpath, '--max-pages', String(max)], { encoding: 'utf8' });
  process.stdout.write(r.stdout); process.stderr.write(r.stderr);
  return r.status === 0;
}

if (import.meta.url === `file://${process.argv[1]}`) main().catch(e => { console.error(e); process.exit(1); });
